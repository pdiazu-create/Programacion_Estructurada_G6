calificacion_1 = float(input("Ingresa la primera calificación: "))
calificacion_2 = float(input("Ingresa la segunda calificación: "))
calificacion_3 = float(input("Ingresa la tercera calificación: "))

promedio = (calificacion_1 + calificacion_2 + calificacion_3) / 3
print(f"El promedio es: {promedio:.2f}")