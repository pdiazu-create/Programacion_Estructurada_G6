# Operadores Aritmeticos suma, resta, multiplicacion, division, porcentaje.

number1 = int(input("Ingresa un numero: "))
number2 = int(input("Ingresa otro numero: "))

print(f"{number1} + {number2} = {number1 + number2}")
print(f"{number1} - {number2} = {number1 - number2}")
print(f"{number1} * {number2} = {number1 * number2}")   
print(f"{number1} / {number2} = {number1 / number2}")
print(f"{number1} % {number2} = {number1 % number2}")