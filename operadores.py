# Solicitar dos números al usuario
numero_1 = float(input("Digite el primer número: "))
numero_2 = float(input("Digite el segundo número: "))

# Realizar y mostrar las operaciones solicitadas
print("\nResultados de las operaciones")
print("Suma:", numero_1 + numero_2)
print("Resta:", numero_1 - numero_2)
print("Multiplicación:", numero_1 * numero_2)
print("División:", numero_1 / numero_2)
print("División entera:", numero_1 // numero_2)
print("Residuo:", numero_1 % numero_2)
print("Potencia:", numero_1 ** numero_2)
